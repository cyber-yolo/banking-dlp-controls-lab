"""Scenario-driven generation with manifest and SHA-256 per file."""

from __future__ import annotations

import csv
import hashlib
import json
import random
import shutil
from datetime import datetime, timezone
from pathlib import Path

import yaml

from dlpgen import __version__
from dlpgen import values as v
from dlpgen.records import build_document
from dlpgen.render import RENDERERS

OUTPUT_MARKER = ".dlpgen-output"
REQUIRED_SCENARIO_KEYS = ("id", "use_case_id", "test_type", "jurisdiction", "data", "expected_policy", "expected_action")
MANIFEST_FIELDS = (
    "file_id", "file_name", "format", "scenario_id", "use_case_id", "test_type", "seed", "data_categories",
    "occurrences", "classification", "jurisdiction", "target_channel", "expected_policy", "expected_action",
    "expected_alert", "expected_result", "sha256", "generated_at", "synthetic_marker",
)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_config(path: Path) -> dict:
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    ids = [s["id"] for s in config["scenarios"]]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate scenario IDs in config")
    for scenario in config["scenarios"]:
        missing = [k for k in REQUIRED_SCENARIO_KEYS if k not in scenario]
        if missing:
            raise ValueError(f"{scenario.get('id', '?')}: missing keys {missing}")
        if scenario["jurisdiction"] not in v.IBAN_LAYOUT:
            raise ValueError(f"{scenario['id']}: unsupported jurisdiction {scenario['jurisdiction']}")
        for fmt in scenario.get("formats", config.get("default_formats", [])):
            if fmt not in RENDERERS:
                raise ValueError(f"{scenario['id']}: unsupported format {fmt}")
    return config


def prepare_output(output_dir: Path) -> None:
    if output_dir.exists() and any(output_dir.iterdir()):
        if not (output_dir / OUTPUT_MARKER).exists():
            raise RuntimeError(f"{output_dir} is not empty and was not created by dlpgen; refusing to overwrite")
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / OUTPUT_MARKER).write_text("Generated by dlpgen. Safe to delete with `python -m dlpgen clean`.\n")


def generate(config_path: Path, output_override: Path | None = None) -> Path:
    config_path = Path(config_path).resolve()
    config = load_config(config_path)
    seed = config["seed"]
    fixed_iso = config.get("document_timestamp", "2026-01-01T00:00:00Z")
    output_dir = output_override or (config_path.parent / config.get("output_dir", "output"))
    output_dir = Path(output_dir).resolve()
    prepare_output(output_dir)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")

    entries = []
    for scenario in config["scenarios"]:
        rng = random.Random(f"{seed}:{scenario['id']}")
        doc, counts = build_document(scenario, rng)
        for fmt in scenario.get("formats", config.get("default_formats", ["txt"])):
            name = f"{scenario['id']}_{scenario['use_case_id']}_{scenario['test_type']}.{fmt}"
            path = output_dir / name
            RENDERERS[fmt](doc, path, fixed_iso)
            entry = {
                "file_id": f"{scenario['id']}-{fmt.upper()}",
                "file_name": name,
                "format": fmt,
                "scenario_id": scenario["id"],
                "use_case_id": scenario["use_case_id"],
                "test_type": scenario["test_type"],
                "seed": f"{seed}:{scenario['id']}",
                "data_categories": [item["category"] for item in scenario["data"]],
                "occurrences": counts,
                "classification": scenario.get("classification", "L1"),
                "jurisdiction": scenario["jurisdiction"],
                "target_channel": scenario.get("target_channel", ""),
                "expected_policy": scenario["expected_policy"],
                "expected_action": scenario["expected_action"],
                "expected_alert": bool(scenario.get("expected_alert", False)),
                "expected_result": scenario.get("expected_result", ""),
                "sha256": sha256_file(path),
                "generated_at": generated_at,
                "synthetic_marker": v.BANNER,
            }
            entry.update(scenario.get("format_overrides", {}).get(fmt, {}))
            entries.append(entry)

    manifest = {
        "generator": "dlpgen",
        "version": __version__,
        "config_file": config_path.name,
        "config_sha256": sha256_file(config_path),
        "seed": seed,
        "generated_at": generated_at,
        "file_count": len(entries),
        "files": entries,
    }
    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    with (output_dir / "manifest.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=MANIFEST_FIELDS, lineterminator="\n")
        writer.writeheader()
        for entry in entries:
            row = dict(entry)
            row["data_categories"] = ";".join(entry["data_categories"])
            row["occurrences"] = ";".join(f"{k}={n}" for k, n in entry["occurrences"].items())
            writer.writerow({k: row.get(k, "") for k in MANIFEST_FIELDS})
    return manifest_path


def clean(output_dir: Path) -> bool:
    output_dir = Path(output_dir)
    if not output_dir.exists():
        return False
    if not (output_dir / OUTPUT_MARKER).exists():
        raise RuntimeError(f"{output_dir} was not created by dlpgen; refusing to delete")
    shutil.rmtree(output_dir)
    return True
